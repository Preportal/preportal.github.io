/* =====================================================================
   PrePortal — publish tool core
   Draft → p/<slug>.js (plus users/, category/, data/ indexes when needed)
   ===================================================================== */
(function () {
  var P = window.PrePortal;

  function q(str) {
    return "'" + String(str == null ? '' : str)
      .replace(/\\/g, '\\\\')
      .replace(/'/g, "\\'")
      .replace(/\r\n?/g, '\n')
      .replace(/\n/g, '\\n') + "'";
  }

  function keys(obj) {
    return Object.keys(obj);
  }

  /** Builds a single post file: p/<slug>.js */
  function buildPostFile(post) {
    var lines = [];
    lines.push('/**');
    lines.push(' * ' + (post.title || 'Untitled'));
    lines.push(' * ' + (P.CFG.siteName || 'PrePortal') + ' · p/' + post.slug + '.js');
    lines.push(' * Generated by the PrePortal publish tool.');
    lines.push(' */');
    lines.push('window.PREPORTAL_POST.register({');
    lines.push('  slug: ' + q(post.slug) + ',');
    lines.push('  title: ' + q(post.title) + ',');
    if (post.excerpt) lines.push('  excerpt: ' + q(post.excerpt) + ',');
    lines.push('  category: ' + q(post.category || 'genel') + ',');
    lines.push('  author: ' + q(post.author || 'preportal') + ',');
    lines.push('  date: ' + q(post.date) + ',');
    if (post.updated) lines.push('  updated: ' + q(post.updated) + ',');
    lines.push('  tags: [' + (post.tags || []).map(q).join(', ') + '],');
    if (post.keywords && post.keywords.length) {
      lines.push('  /* SEO: arama ve robotlar için, sayfada gösterilmez */');
      lines.push('  keywords: [');
      post.keywords.forEach(function (k, i, arr) {
        lines.push('    ' + q(k) + (i === arr.length - 1 ? '' : ','));
      });
      lines.push('  ],');
    }
    if (post.cover) lines.push('  cover: ' + q(post.cover) + ',');
    if (post.featured) lines.push('  featured: true,');
    if (post.version) lines.push('  version: ' + q(post.version) + ',');
    if (post.size) lines.push('  size: ' + q(post.size) + ',');
    if (post.platform) lines.push('  platform: ' + q(post.platform) + ',');
    if (post.rating != null && post.rating !== '') lines.push('  rating: ' + Number(post.rating) + ',');
    if (post.downloads && post.downloads.length) {
      lines.push('  downloads: [');
      post.downloads.forEach(function (d) {
        lines.push('    { label: ' + q(d.label || 'Download') + ', url: ' + q(d.url || '') +
          (d.version ? ', version: ' + q(d.version) : '') +
          (d.size ? ', size: ' + q(d.size) : '') + ' }' + (d === post.downloads[post.downloads.length - 1] ? '' : ','));
      });
      lines.push('  ],');
    }
    lines.push('  content: ' + q(post.content || ''));
    lines.push('});');
    lines.push('');
    return lines.join('\n');
  }

  /** Category file: category/<slug>.js (alt kategori: parent) */
  function buildCategoryFile(cat) {
    var lines = ['window.PREPORTAL_CATEGORY.register({'];
    lines.push('  slug: ' + q(cat.slug) + ',');
    if (cat.parent) lines.push('  parent: ' + q(cat.parent) + ',');
    lines.push('  name: ' + q(cat.name) + ',');
    lines.push('  description: ' + q(cat.description || '') + ',');
    lines.push('  icon: ' + q(cat.icon || 'folder') + ',');
    if (cat.order) lines.push('  order: ' + Number(cat.order) + ',');
    var keys = Array.isArray(cat.keywords) ? cat.keywords : String(cat.keywords || '').split(',');
    keys = keys.map(function (k) { return String(k || '').trim(); }).filter(Boolean);
    if (keys.length) {
      lines.push('  /* SEO: aramada kullanılır, sayfada gösterilmez */');
      lines.push('  keywords: [' + keys.map(q).join(', ') + ']');
    }
    return lines.join('\n').replace(/,\s*$/, '') + '\n});\n';
  }

  /** Author file: users/<slug>.js */
  function buildUserFile(user) {
    var lines = ['window.PREPORTAL_USER.register({'];
    lines.push('  slug: ' + q(user.slug) + ',');
    lines.push('  name: ' + q(user.name) + ',');
    lines.push('  role: ' + q(user.role || '') + ',');
    lines.push('  avatar: ' + q(user.avatar || '') + ',');
    lines.push('  bio: ' + q(user.bio || '') + (user.email || user.links ? ',' : ''));
    if (user.email) lines.push('  email: ' + q(user.email) + (user.links && Object.keys(user.links).length ? ',' : ''));
    if (user.links && Object.keys(user.links).length) {
      lines.push('  links: {');
      var ks = Object.keys(user.links);
      ks.forEach(function (k, i) {
        lines.push('    ' + q(k) + ': ' + q(user.links[k]) + (i === ks.length - 1 ? '' : ','));
      });
      lines.push('  }');
    }
    return lines.join('\n').replace(/,\s*$/, '') + '\n});\n';
  }

  /** data/runtime.js — custom CSS / JS / ads (admin panel) */
  function buildRuntimeFile(rt) {
    return [
      '/**',
      ' * PrePortal — runtime overrides (custom CSS, custom JS, extra head HTML, ads)',
      ' * Generated by the admin panel. Loaded after data/config.js on every page.',
      ' */',
      'window.PREPORTAL_RUNTIME = {',
      '  customCss: ' + q(rt.customCss || '') + ',',
      '  customJs: ' + q(rt.customJs || '') + ',',
      '  headHtml: ' + q(rt.headHtml || '') + ',',
      '  ads: {',
      '    enabled: ' + (rt.ads && rt.ads.enabled ? 'true' : 'false') + ',',
      '    slots: ' + JSON.stringify((rt.ads && rt.ads.slots) || [], null, 2).split('\n').join('\n    '),
      '  }',
      '};',
      ''
    ].join('\n');
  }

  /** data/config.js — site settings from the admin panel */
  function buildConfigFile(cfg) {
    var langs = Array.isArray(cfg.langs) ? cfg.langs : String(cfg.langs || '').split(',');
    langs = langs.map(function (l) { return String(l).trim(); }).filter(Boolean);
    var int = function (v, d) { var n = parseInt(v, 10); return isNaN(n) ? d : n; };
    return [
      '/**',
      ' * PrePortal — site configuration',
      ' * Generated by the admin panel. Every page loads this file first.',
      ' * Interface strings live in lang/<code>.json, not here.',
      ' */',
      'window.PREPORTAL_CONFIG = {',
      '  siteName: ' + q(cfg.siteName || 'PrePortal') + ',',
      '  siteUrl: ' + q(cfg.siteUrl || 'https://example.github.io/preportal/') + ',',
      '  description: ' + q(cfg.description || '') + ',',
      '  logo: ' + q(cfg.logo || 'assets/img/logo.png') + ',',
      '',
      '  langs: [' + langs.map(q).join(', ') + '],',
      '  defaultLang: ' + q(langs[0] || 'en') + ',',
      '  langDir: ' + q(cfg.langDir || 'lang') + ',',
      '',
      '  postsDir: ' + q(cfg.postsDir || 'p') + ',',
      '  usersDir: ' + q(cfg.usersDir || 'users') + ',',
      '  categoryDir: ' + q(cfg.categoryDir || 'category') + ',',
      '  mediaDir: ' + q(cfg.mediaDir || 'assets/img') + ',',
      '',
      '  media: {',
      '    mode: ' + q((cfg.media && cfg.media.mode) || 'repo') + ',',
      '    imgbbKey: ' + q((cfg.media && cfg.media.imgbbKey) || '') + ',',
      '    githubToken: ' + q((cfg.media && cfg.media.githubToken) || '') + ',',
      '    githubOwner: ' + q((cfg.media && cfg.media.githubOwner) || '') + ',',
      '    githubRepo: ' + q((cfg.media && cfg.media.githubRepo) || '') + ',',
      '    githubBranch: ' + q((cfg.media && cfg.media.githubBranch) || 'main') + '',
      '  },',
      '',
      '  disqus: {',
      '    shortname: ' + q((cfg.disqus && cfg.disqus.shortname) || '') + ',',
      '    pageIdentifier: ' + q((cfg.disqus && cfg.disqus.pageIdentifier) || 'url') + '',
      '  },',
      '',
      '  perPage: ' + int(cfg.perPage, 12) + ',',
      '',
      '  intro: { enabled: ' + (cfg.intro && cfg.intro.enabled ? 'true' : 'false') + ', key: ' + q((cfg.intro && cfg.intro.key) || 'intro.main') + ' },',
      '',
      '  social: {',
      '    telegram: ' + q((cfg.social && cfg.social.telegram) || '') + ',',
      '    x: ' + q((cfg.social && cfg.social.x) || '') + ',',
      '    github: ' + q((cfg.social && cfg.social.github) || '') + ',',
      '    rss: ' + q((cfg.social && cfg.social.rss) || '') + '',
      '  },',
      '};',
      ''
    ].join('\n');
  }

  /** Postfile rebuild from a loaded post (edit mode) */
  function buildPostFromExisting(post) {
    return buildPostFile(post);
  }

  /** Rebuilds an index file (data/posts.js etc.) from the given list */
  function buildIndexFile(varName, list, comment) {
    return [
      '/**',
      ' * ' + comment,
      ' */',
      'window.' + varName + ' = [',
      list.map(function (id) { return '  ' + q(id); }).join(',\n'),
      '];',
      ''
    ].join('\n');
  }

  /** Adds a new id to an existing index (returns it unchanged if present) */
  function withId(list, id) {
    var arr = (list || []).slice();
    if (arr.indexOf(id) === -1) arr.push(id);
    return arr;
  }

  /** Lightweight JS syntax highlighting (for copy/preview): escape first, then a single tokenizer pass */
  function highlight(code) {
    var src = String(code);
    var re = /(\/\*[\s\S]*?\*\/)|(^\s*\/\/.*$)|('(?:[^'\\]|\\.)*')|\b(window|true|false|null|undefined)\b|\b(\d+(?:\.\d+)?)\b/gm;
    var out = '';
    var last = 0;
    var m;
    while ((m = re.exec(src)) !== null) {
      out += P.esc(src.slice(last, m.index));
      if (m[1] || m[2]) out += '<span class="tok-com">' + P.esc(m[0]) + '</span>';
      else if (m[3]) out += '<span class="tok-str">' + P.esc(m[0]) + '</span>';
      else if (m[4]) out += '<span class="tok-key">' + P.esc(m[0]) + '</span>';
      else if (m[5]) out += '<span class="tok-num">' + P.esc(m[0]) + '</span>';
      last = re.lastIndex;
    }
    out += P.esc(src.slice(last));
    return out;
  }

  P.publish = {
    q: q,
    buildPostFile: buildPostFile,
    buildCategoryFile: buildCategoryFile,
    buildUserFile: buildUserFile,
    buildIndexFile: buildIndexFile,
    buildRuntimeFile: buildRuntimeFile,
    buildConfigFile: buildConfigFile,
    buildPostFromExisting: buildPostFromExisting,
    withId: withId,
    highlight: highlight
  };
})();
